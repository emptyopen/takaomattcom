const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const source = ts.transpileModule(fs.readFileSync('src/app/wealth-map/model.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
const context={exports:{}}; vm.runInNewContext(source,context);
const {median,globalIndex,color}=context.exports;
const meta=JSON.parse(fs.readFileSync('public/wealth-data/meta.json'));
assert.equal(median([]),null);
assert.equal(median([0,NaN,2,4]),3);
assert.equal(globalIndex(null,'country',meta),null);
assert.equal(globalIndex(-1,'Block group',meta),null);
assert.equal(globalIndex(meta.worldGDP,'country',meta),1);
assert.equal(globalIndex(meta.usIncome,'Block group',meta),globalIndex(meta.usGDP,'country',meta));
assert.equal(color(1,1),color(4,4));
assert.notEqual(color(1,1),color(4,1));
assert.equal(color(null,1),'#29353e');
const sf=JSON.parse(fs.readFileSync('public/wealth-data/san-francisco.json'));
const ca=JSON.parse(fs.readFileSync('public/wealth-data/us-06.json'));
assert(sf.features.length>100);
const missing=sf.features.filter(f=>!Object.hasOwn(ca,f.properties.GEOID)).map(f=>f.properties.GEOID);
assert.deepEqual(missing,['060014251012'], 'Review any new missing ACS joins; known unmatched boundary is displayed without an estimate');
assert.equal(new Set(sf.features.map(f=>f.properties.GEOID)).size,sf.features.length);
const world=JSON.parse(fs.readFileSync('public/wealth-data/world.json'));
assert(world.features.filter(f=>f.properties.value>0).length>150);
assert.equal(world.features.find(f=>f.properties.id==='USA').properties.value,meta.usGDP);
console.log(`Passed scale, missing-data, national anchor, and snapshot checks (${sf.features.length} starter block groups).`);
